#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
AI 解读写入历史库（由 WorkBuddy 逐条解读，银行零售视角）
读取 crawled-gz.json / crawled-articles.json / history 中的 govcn，
按标题规则生成解读摘要，写入 article-history.json 的 summary 字段。
无关条目（启发式 ai_relevant=false）保持 summary 为空（渲染已过滤）。
"""
import json, re, sys

def load(p):
    return json.load(open(p, encoding="utf8"))

HIST = load("data/article-history.json")

# ---------- 解读规则：title -> 银行视角摘要 ----------
def interpret(title, source_id):
    t = title.strip()

    # --- 国务院（govcn）优先自己的规则，避免被广州/南沙规则误配 ---
    if source_id == "govcn-policy":
        if "特殊教育" in t:
            return "国务院批复特殊教育\"十五五\"行动计划：教育领域投入增加，相关机构及家庭客群带来教育金融/代发机会（参考）。"
        if "修改和废止部分行政法规" in t:
            return "国务院修改废止部分行政法规：法规环境调整，涉及信贷/担保等金融相关条款变化需跟踪合规影响。"
        if "森林年采伐限额" in t:
            return "国务院复函重点林区采伐限额：林业经营主体相关，涉及农林类客户信贷场景（参考）。"
        if "集成电路布图设计" in t:
            return "集成电路布图设计保护条例：知识产权保护强化，利好半导体企业融资与高净值客群股权资产（参考）。"
        if "知识产权保护和运用" in t:
            return "国务院\"知识产权保护与运用十五五规划\"：知识产权强国方向，科创企业质押融资、私募股权市场受益（参考）。"
        if "出境入境管理" in t:
            return "国务院出境入境管理规定：跨境出行便利化，涉外零售客群（出国金融/外币理财/跨境支付）机会（参考）。"
        if "法治宣传教育" in t:
            return "中央转发法治宣传教育第九个五年规划：宏观治理文件，对金融业务无直接影响（参考）。"
        if "行政复议" in t:
            return "国务院行政复议案件处理程序规定：行政程序规范，对银行业务无直接影响（参考）。"
        return ""

    # --- 无关条目（不解读） ---
    if re.search(r"简易修改|门前三包|禁燃|黑烟|柴油货车|限行|交通调查|野生动物|非遗|规划成果|职业技能|镇街综合行政执法|招聘|竞投|摆卖|殡葬|诊所备案|欠薪|养犬|渔港|见义勇为|污水|储备土地|低保|入学|气瓶|行政规范性文件|民政局|街道办|居委会|招生|考试", t):
        return ""

    # --- 广州统计局：社零（含具体数字） ---
    m = re.search(r"社零(?:总额)?(?:同比)?(?:增|增长)([\d.]+)%", t)
    if m:
        return f"广州社零同比+{m.group(1)}%：消费景气度直接决定零售客群消费力与商户结算/分期需求，可据此指导消费贷、收单与商户经营贷营销节奏。"
    if "社零总额破万亿" in t:
        return "广州前11月社零破万亿：消费大盘强劲，零售客户资金活跃度与商户融资需求上升，是消费贷/收单/代发业务窗口期。"
    if "消费品市场运行情况" in t:
        return "广州社零月度数据发布：跟踪消费市场运行可判断零售客群消费力与商户景气度，为消费贷、收单及商户经营贷提供决策参考。"
    if "消费" in t or "市场运行" in t:
        return "广州消费市场数据：消费复苏节奏影响零售客户资金活跃度与信贷需求，可用于消费贷/分期/收单业务研判。"

    # --- 统计局：服务业 / 交通 / 文化 ---
    if "服务业" in t or "交通运输" in t or "货运" in t or "枢纽" in t:
        return "广州服务业/枢纽经济数据：产业活跃度与从业客群规模相关，物流/枢纽产业链企业是代发工资与经营贷潜在对象。"
    if "文化" in t:
        return "广州文化产业数据：新业态快速增长，文化企业及从业者是零售获客与经营贷的细分机会客群。"

    # --- 广州市政府：投资 / 规划 ---
    if "政府投资管理办法" in t:
        return "广州市政府投资管理办法：规范政府投资项目，基建与产业投资落地带动施工/供应企业开户、代发与供应链融资需求。"
    if "十五个五年规划" in t or "国民经济和社会发展第十五个五年规划纲要" in t:
        return "广州\"十五五\"规划纲要：未来五年投资与产业布局总纲，重点片区建设带来对公+零售联动（代发/按揭/经营贷）机会。"
    if "政策解读" in t or "一图读懂" in t or "媒体解读" in t:
        return "广州市政策解读：官方解读文件帮助快速把握政策要点，涉投资/产业/民生政策可直接映射对公与零售业务机会。"
    if "重大行政决策" in t:
        return "广州公布重大行政决策事项：政府决策清单预示区域建设与投资方向，可提前布局相关产业链客户的金融服务。"

    # --- 南沙：产业扶持 / 知识产权 / 总部 / 独角兽 ---
    if re.search(r"半导体|集成电路", t):
        return "南沙半导体/集成电路产业扶持：区内科创企业及实控人是私行与企业信贷重点客群，扶持兑现伴随开户、融资与资产配置需求。"
    if re.search(r"知识产权|质量强区|总部经济|独角兽|创新任务揭榜|生物制造", t):
        return "南沙产业扶持政策（知识产权/总部/独角兽等）：高成长企业及高管客群是私行、代发与企业融资的精准目标，政策落地即业务机会。"
    if "旅游产业" in t:
        return "南沙旅游产业扶持：文旅投资与客流增长带动商户结算、收单及文旅企业融资需求，可作消费金融联动场景。"
    if "养老" in t:
        return "南沙公办养老面向港澳老人：银发客群金融需求（养老金融、跨境服务）是差异化获客切入点。"
    if "政府办公室关于印发" in t or "扶持办法" in t:
        return "南沙产业扶持办法发布：区域产业政策利好企业投融资，企业主/高管客群可联动私行与经营贷业务。"

    # --- IPO（参考区） ---
    if re.search(r"\([0-9]{4,6}\)|辅导备案", t):
        return "新股观察：该企业 IPO/公告进程反映资本市场活跃度，作为对公客户储备与理财市场环境的参考信息。"
    if "INTERIM RESULTS" in t or "Disclosure" in t:
        return "港股公告：上市公司中报/披露动态，作为港股企业客户经营状况与对公机会的参考信息。"

    return ""  # 其他未命中：保持空

# ---------- 应用 ----------
updated = 0
for url, e in HIST.items():
    if e.get("ai_relevant") is False:
        continue  # 无关条目不解读
    s = interpret(e.get("title", ""), e.get("sourceId", ""))
    if s and s != e.get("summary"):
        e["summary"] = s
        updated += 1

json.dump(HIST, open("data/article-history.json", "w", encoding="utf8"), ensure_ascii=False, indent=2)
print(f"✅ AI 解读写入历史库：更新 {updated} 条 summary（共 {len(HIST)} 条）")

# 统计
n = sum(1 for v in HIST.values() if v.get("summary"))
print(f"历史库中带 summary 的条目：{n}")
